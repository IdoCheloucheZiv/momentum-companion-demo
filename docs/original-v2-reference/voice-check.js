const {JSDOM}=require('jsdom');
const fs=require('fs'), assert=require('node:assert/strict');
let spoken=[], recognizer;
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://localhost/',runScripts:'dangerously',beforeParse(w){
  w.isSecureContext=true;
  w.SpeechSynthesisUtterance=class {constructor(text){this.text=text;}};
  w.speechSynthesis={getVoices:()=>[{name:'English',lang:'en-US',voiceURI:'en'},{name:'Hebrew',lang:'he-IL',voiceURI:'he'}],cancel(){},speak(u){spoken.push(u);}};
  w.SpeechRecognition=class {constructor(){recognizer=this;} start(){} stop(){this.onend();}};
}});
const w=dom.window,d=w.document;
d.getElementById('btnStart').click();
d.getElementById('btnVoice').click();
assert.equal(spoken.length,1); assert.equal(spoken[0].lang,'he-IL');
d.getElementById('btnAI').click();
const links=[...d.querySelectorAll('#dBody a')];
assert.equal(links.length,4); assert(links.every(a=>a.target==='_blank' && a.rel==='noopener noreferrer' && !a.href.includes('?')));
d.getElementById('btnMic').click();
const count=w.eval('S.messages.length');
d.getElementById('input').value='unsent draft';
recognizer.onerror({error:'not-allowed'}); recognizer.onend();
assert.match(d.getElementById('hint').textContent,/נדחתה/); assert.equal(w.eval('S.messages.length'),count);
d.getElementById('btnLang').click();
assert.equal(d.getElementById('btnAI').textContent,'Ask an AI'); assert.equal(d.documentElement.dir,'ltr');
d.getElementById('btnMic').click(); recognizer.start=()=>{throw Error('failed');};
recognizer.onerror({error:'network'}); recognizer.onend(); assert.match(d.getElementById('hint').textContent,/internet/);
d.getElementById('btnMic').click();
recognizer.onresult({resultIndex:0,results:[Object.assign([{transcript:'hello'}],{isFinal:true})]});
recognizer.onend(); assert.equal(w.eval('S.messages.length'),count+1);
console.log('PASS: current reply playback, Hebrew voice, external links, language switch, microphone error preservation and transcript send');
setTimeout(() => dom.window.close(), 100);
